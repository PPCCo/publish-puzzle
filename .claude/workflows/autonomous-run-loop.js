export const meta = {
  name: 'autonomous-run-loop',
  description: 'Advance one product through valid non-gate stages, stopping at every human gate with a prepared packet. Never approves, freezes, releases, or submits.',
  phases: [
    { title: 'Plan', detail: 'read deterministic next-action', model: '@bedrock-eus1/us.anthropic.claude-haiku-4-5-20251001-v1:0' },
    { title: 'Decide', detail: 'classify stop/proceed token', model: '@bedrock-eus1/us.anthropic.claude-haiku-4-5-20251001-v1:0' },
    { title: 'Gate', detail: 'assemble gate packet', model: '@bedrock-eus1/us.anthropic.claude-sonnet-5' },
    { title: 'Stage', detail: 'execute one publishing stage', model: '@bedrock-eus2/us.anthropic.claude-opus-4-8' },
    { title: 'Report', detail: 'autonomous-run report', model: '@bedrock-eus1/us.anthropic.claude-sonnet-5' },
  ],
}

// args: { projectId, until?: "human-gate"|"<STATE>", max_stages?: number }
const input = args ?? {}
const projectId = input.projectId
if (!projectId) {
  return 'ERROR: autonomous-run-loop requires args.projectId'
}
const until = input.until ?? 'human-gate'
// Hard cap of 5 completed stages (mirrors /product-run). Requested value is clamped.
const maxStages = Math.max(1, Math.min(Number(input.max_stages ?? 3) || 3, 5))

const cli = '${CLAUDE_PROJECT_DIR}/.venv/bin/python3 .claude/scripts/ph_cli.py'

// The loop is deterministic in its SEQUENCING and STOP conditions; the actual
// artifact production is delegated to bounded specialist agents. The workflow
// runtime cannot touch the filesystem, so each step is executed by an agent that
// runs the deterministic CLI verbs (project plan / transition, approval packet)
// and the mapped stage skills. No step may ever call an approval / freeze /
// release / submission / spending / legal-acceptance skill.

const completed = []
let stopReason = null
let lastPlan = null

for (let stage = 1; stage <= maxStages; stage += 1) {
  // 1. Deterministic recommendation for the current state.
  const planText = await agent(
    `Return ONLY the raw JSON from: ${cli} project plan ${projectId}. Do not modify state. Do not run any other command.`,
    { label: `plan-${stage}`, phase: 'Plan', model: '@bedrock-eus1/us.anthropic.claude-haiku-4-5-20251001-v1:0', effort: 'low' },
  )
  lastPlan = planText

  // 2. Decide, deterministically, from the plan's autonomy_action.
  const decision = await agent(
    `You are the run-loop sequencer. Given this plan JSON, output ONE token only:
- "STOP_GATE" if autonomy_action is "STOP_AT_GATE" or is_human_gate is true
- "STOP_BLOCKED" if autonomy_action is "BLOCKED"
- "STOP_TERMINAL" if autonomy_action is "TERMINAL"
- "STOP_TARGET" if the plan's current_state already equals the requested until state "${until}" (and until is not "human-gate")
- "PROCEED" otherwise
Plan JSON: ${planText}`,
    { label: `decide-${stage}`, phase: 'Decide', model: '@bedrock-eus1/us.anthropic.claude-haiku-4-5-20251001-v1:0', effort: 'low' },
  )
  const token = String(decision).trim().toUpperCase()

  if (token.includes('STOP_GATE')) {
    // 3a. HUMAN GATE: assemble and present the packet, then STOP. Never approve.
    const packet = await agent(
      `The project is at a human gate. Extract required_gate from this plan JSON, then run:
${cli} approval packet ${projectId} --gate <required_gate>
Return the packet JSON and the exact /product-approve-* (or /product-freeze, /product-release-authorize) command a human must run. Do NOT grant, freeze, release, or transition. Do NOT invoke any human-only skill yourself.
Plan JSON: ${planText}`,
      { label: `gate-packet-${stage}`, phase: 'Gate', model: '@bedrock-eus1/us.anthropic.claude-sonnet-5', effort: 'medium' },
    )
    stopReason = { type: 'HUMAN_GATE', stage, packet }
    break
  }
  if (token.includes('STOP_BLOCKED')) {
    stopReason = { type: 'BLOCKED', stage, plan: planText }
    break
  }
  if (token.includes('STOP_TERMINAL')) {
    stopReason = { type: 'AUTONOMY_TERMINAL', stage, plan: planText }
    break
  }
  if (token.includes('STOP_TARGET')) {
    stopReason = { type: 'REACHED_TARGET', stage, plan: planText }
    break
  }

  // 3b. PROCEED: run the mapped stage with bounded specialist agents, then
  // register/verify/gate and transition via the deterministic CLI.
  const work = await agent(
    `Execute exactly one publishing stage for project ${projectId}, staying within the recorded plan.
Plan JSON: ${planText}

Rules:
- Delegate only the recommended_skills / recommended_agents / recommended_workflows from the plan, with exact input hashes, output paths, and acceptance tests.
- Content is generated by code and independently verified by code: a generator never signs off its own verification. Run ${cli} generate then a separate ${cli} verify before treating a batch as done.
- Respect maximum_full_revision_cycles from .claude/config/quality_gates.json: do not exceed the configured full generation->review->revision cycles for this project; if that would be exceeded, STOP and report instead.
- After producing artifacts: register them (artifact register), run the relevant deterministic validator/gate, and reconcile findings.
- Only transition with: ${cli} project transition ${projectId} --to <target_state> --actor autonomous-run-loop --reason "<stage summary>"
- The transition will (correctly) fail if any blocker remains; treat that failure as a STOP, not something to work around.
- NEVER invoke approval, freeze, release, submission, incident, spending, legal-acceptance, or live-listing skills. NEVER edit state.json directly.
Return: the target_state reached (or the exact blocker that stopped you), artifacts + hashes created, and validator/gate decisions.`,
    { label: `stage-${stage}`, phase: 'Stage', model: '@bedrock-eus2/us.anthropic.claude-opus-4-8', effort: 'high' },
  )
  completed.push({ stage, result: work })

  if (until !== 'human-gate' && String(work).includes(until)) {
    stopReason = { type: 'REACHED_TARGET', stage, plan: planText }
    break
  }
}

if (!stopReason) {
  stopReason = { type: 'STAGE_CAP', maxStages }
}

// Final synthesis: an autonomous-run report. Advisory only; records nothing.
return await agent(
  `Produce the bounded autonomous-run report for project ${projectId}. Summarize completed stages, agents/workflows used, artifacts and hashes, validator/gate decisions, the exact stop reason, and the next valid HUMAN action (including the /product-approve-* command and packet path when the stop is a human gate). Confirm no approval/freeze/release/submission occurred. Recommend writing this to release/autonomous-run-latest.json.
Completed stages: ${JSON.stringify(completed)}
Stop: ${JSON.stringify(stopReason)}
Last plan: ${lastPlan}`,
  { label: 'autonomous-run-report', phase: 'Report', model: '@bedrock-eus1/us.anthropic.claude-sonnet-5', effort: 'high' },
)
